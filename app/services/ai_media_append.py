with open('D:\\\\iNew\\\\app\\\\services\\\\ai_media.py', 'a') as f:
    f.write('\\n')
    f.write('def _download_remote(self, url: str) -> bytes:\\n')
    f.write('    \"\"\"Download remote content\"\"\"\\n')
    f.write('    response = requests.get(url, timeout=30)\\n')
    f.write('    response.raise_for_status()\\n')
    f.write('    return response.content\\n')
    f.write('\\n')
    f.write('def _error_text(self, text: str) -> str:\\n')
    f.write('    \"\"\"Process and clean error text\"\"\"\\n')
    f.write('    # Remove HTML tags and special characters\\n')
    f.write('    clean = re.sub(r\"<[^>]+>\", \"\", text)\\n')
    f.write('    clean = re.sub(r\"[\\t\\n\\r\\s]+\", \" \", clean)\\n')
    f.write('    clean = re.sub(r\"[\\t\\n\\r\\s]{2,}\", \" \", clean)\\n')
    f.write('    return clean.strip()\\n')
    f.write('\\n')
    f.write('def _execute(self, command: str) -> dict:\\n')
    f.write('    \"\"\"Execute shell command and return result\"\"\"\\n')
    f.write('    try:\\n')
    f.write('        result = subprocess.run(\\n')
    f.write('            shell=True,\\n')
    f.write('            command=command,\\n')
    f.write('            capture_output=True,\\n')
    f.write('            text=True,\\n')
    f.write('            timeout=30\\n')
    f.write('        )\\n')
    f.write('        return {\\n')
    f.write('            \"return_code\": result.returncode,\\n')
    f.write('            \"stdout\": result.stdout,\\n')
    f.write('            \"stderr\": result.stderr,\\n')
    f.write('            \"success\": result.returncode == 0\\n')
    f.write('        }\\n')
    f.write('    except Exception as e:\\n')
    f.write('        return {\\n')
    f.write('            \"error\": str(e),\\n')
    f.write('            \"success\": False\\n')
    f.write('        }\\n')
    f.write('\\n')
    f.write('def chunks(self, data: bytes, chunk_size: int = 1024) -> Iterator[bytes]:\\n')
    f.write('    \"\"\"Yield chunks of data\"\"\"\\n')
    f.write('    for i in range(0, len(data), chunk_size):\\n')
    f.write('        yield data[i:i + chunk_size]\\n')
    f.write('\\n')
    f.write('def clean_srt(self, srt_content: str) -> str:\\n')
    f.write('    \"\"\"Clean SRT subtitle file\"\"\"\\n')
    f.write('    lines = srt_content.split(\"\\n\")\\n')
    f.write('    cleaned = []\\n')
    f.write('    for line in lines:\\n')
    f.write('        line = line.strip()\\n')
    f.write('        if line and not line.startswith(\"\\ufeff\"):\\n')
    f.write('            cleaned.append(line)\\n')
    f.write('    return \"\\n\".join(cleaned)\\n')
    f.write('\\n')
    f.write('def delete_uploaded(self, file_path: str) -> bool:\\n')
    f.write('    \"\"\"Delete uploaded file\"\"\"\\n')
    f.write('    try:\\n')
    f.write('        if os.path.exists(file_path):\\n')
    f.write('            os.remove(file_path)\\n')
    f.write('            return True\\n')
    f.write('        return False\\n')
    f.write('    except Exception:\\n')
    f.write('        return False\\n')
    f.write('\\n')
    f.write('def generate(self, image_data: bytes, prompt: str) -> dict:\\n')
    f.write('    \"\"\"Generate image from data and prompt\"\"\"\\n')
    f.write('    import io\\n')
    f.write('    image = Image.open(io.BytesIO(image_data))\\n')
    f.write('    # Mock implementation - in real app this would call actual AI model\\n')
    f.write('    return {\\n')
    f.write('        \"success\": True,\\n')
    f.write('        \"image_size\": f\"{image.width}x{image.height}\",\\n')
    f.write('        \"prompt\": prompt[:100] + \"...\" if len(prompt) > 100 else prompt,\\n')
    f.write('        \"model\": \"mock_ai_model\",\\n')
    f.write('        \"processing_time\": 1.5\\n')
    f.write('    }\\n')
    f.write('\\n')
    f.write('def nd(self, text: str) -> str:\\n')
    f.write('    \"\"\"Normalize text - remove special chars, normalize whitespace\"\"\"\\n')
    f.write('    # Remove special characters but keep letters, numbers and basic punctuation\\n')
    f.write('    cleaned = re.sub(r\"[^\\w\\s\".\"\\-!?.,;:]\", \" \", text)\\n')
    f.write('    cleaned = re.sub(r\"\\s+\", \" \", cleaned)\\n')
    f.write('    return \" \".join(cleaned).strip()\\n')
    f.write('\\n')
    f.write('def upload_video(self, video_path: str, destination: str) -> bool:\\n')
