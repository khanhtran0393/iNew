with open('D:\\\\iNew\\\\app\\\\services\\\\ai_copilot.py', 'a') as f:
    f.write('\\n')
    f.write('    @staticmethod\n')
    f.write('    def _topic_id_for_post(self, post_id: int) -> Optional[int]:\n')
    f.write('        \"\"\"Get topic ID associated with a post\"\"\"\n')
    f.write('        post = db.query(RawPost).filter(RawPost.id == post_id).first()\\n')
    f.write('        if post and post.source_channel_id:\\n')
    f.write('            channel = db.query(SourceChannel).filter(SourceChannel.id == post.source_channel_id).first()\\n')
    f.write('            if channel and hasattr(channel, \"topic_sources\") and channel.topic_sources:\\n')
    f.write('                return channel.topic_sources[0].topic_id\\n')
    f.write('        return None\\n')
    f.write('\\n')
    f.write('    @staticmethod\\n')
    f.write('    def i_usage_today() -> dict:\\n')
    f.write('        \"\"\"Get today\'s AI usage statistics\"\"\"\\n')
    f.write('        today = datetime.utcnow().date()\\n')
    f.write('        usage = db.query(AiUsageLog).filter(AiUsageLog.created_at >= datetime.combine(today, datetime.min.time())).all()\\n')
    f.write('        total_tokens = sum(log.tokens_used for log in usage) if usage else 0\\n')
    f.write('        return {\\n')
    f.write('            \"date\": str(today),\\n')
    f.write('            \"total_tokens\": total_tokens,\\n')
    f.write('            \"count\": len(usage),\\n')
    f.write('            \"average_tokens\": total_tokens / len(usage) if usage else 0\\n')
    f.write('        }\\n')
    f.write('\\n')