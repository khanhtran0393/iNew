with open('D:\\\\iNew\\\\app\\\\services\\\\ai_key_router.py', 'a') as f:
    f.write('\\n')
    f.write('def dd(key_id: int) -> dict:\\n')
    f.write('    \"\"\"Get AI key details by ID\"\"\"\\n')
    f.write('    key = db.query(AiApiKey).filter(AiApiKey.id == key_id).first()\\n')
    f.write('    if not key:\\n')
    f.write('        raise ValueError(f\"AI key with ID {key_id} not found\")\\n')
    f.write('    return {\\n')
    f.write('        \"id\": key.id,\\n')
    f.write('        \"provider\": key.provider,\\n')
    f.write('        \"label\": key.label,\\n')
    f.write('        \"is_active\": key.is_active,\\n')
    f.write('        \"created_at\": key.created_at.isoformat() if key.created_at else None\\n')
    f.write('    }\\n')
    f.write('\\n')
    f.write('def find_best_ai_key(text_content: str) -> AiApiKey:\\n')
    f.write('    \"\"\"Find the best AI key for given text content\"\"\"\\n')
    f.write('    # Simple heuristic: match by keywords\\n')
    f.write('    keywords = {\\n')
    f.write('        \"gpt\": [\"gpt\", \"openai\", \"chatgpt\"],\\n')
    f.write('        \"gemini\": [\"gemini\", \"google\", \"gemini ai\"],\\n')
    f.write('        \"claude\": [\"claude\", \"anthropic\"],\\n')
    f.write('        \"llama\": [\"llama\", \"llama2\", \"llama3\"],\\n')
    f.write('    }\\n')
    f.write('    text_lower = text_content.lower()\\n')
    f.write('    best_key = None\\n')
    f.write('    max_score = 0\\n')
    f.write('    for key in db.query(AiApiKey).all():\\n')
    f.write('        score = 0\\n')
    f.write('        for keyword in keywords.get(key.provider.lower(), []):\\n')
    f.write('            if keyword in text_lower:\\n')
    f.write('                score += 1\\n')
    f.write('        if score > max_score:\\n')
    f.write('            max_score = score\\n')
    f.write('            best_key = key\\n')
    f.write('    if not best_key:\\n')
    f.write('        raise ValueError(\"No suitable AI key found for content\")\\n')
    f.write('    return best_key\\n')
    f.write('\\n')
    f.write('def get_purpose_meta(purpose: str) -> dict:\\n')
    f.write('    \"\"\"Get metadata for a given purpose\"\"\"\\n')
    f.write('    purpose_lower = purpose.lower()\\n')
    f.write('    metadata = {\\n')
    f.write('        \"gpt\": {\\n')
    f.write('            \"description\": \"OpenAI GPT models\",\\n')
    f.write('            \"capabilities\": [\"text_completion\", \"summarization\", \"translation\"],\\n')
    f.write('            \"limitations\": [\"rate_limited\", \"cost_based\"]\\n')
    f.write('        },\\n')
    f.write('        \"gemini\": {\\n')
    f.write('            \"description\": \"Google Gemini models\",\\n')
    f.write('            \"capabilities\": [\"multimodal\", \"reasoning\", \"code\"],\\n')
    f.write('            \"limitations\": [\"context_length\", \"safety_filters\"]\\n')
    f.write('        },\\n')
    f.write('        \"claude\": {\\n')
    f.write('            \"description\": \"Anthropic Claude models\",\\n')
    f.write('            \"capabilities\": [\"analysis\", \"summarization\", \"translation\"],\\n')
    f.write('            \"limitations\": [\"token_window\", \"safety]\\n')
    f.write('        },\\n')
    f.write('    }\\n')
    f.write('    return metadata.get(purpose_lower, {\"error\": \"unknown purpose\"})\\n')